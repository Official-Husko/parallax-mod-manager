package library

import (
	"context"
	"sync"

	"golang.org/x/sync/errgroup"

	"github.com/Official-Husko/parallax-mod-manager/internal/steamapi"
)

// maxConcurrentProfileFetches bounds how many profile requests Get makes
// at once. Steam Community is a shared third-party service, not local
// disk - deliberately low, matching internal/dlcstore's own concurrency
// cap for the same reason.
const maxConcurrentProfileFetches = 5

// AuthorProfile pairs a SteamID64 with its real Steam Community profile -
// a self-identifying element for a slice-returned Wails-bound method
// (app.go's AuthorProfiles), rather than a map keyed by SteamID64. See
// WorkshopDetailsCache's own doc comment for why: a struct only ever
// reachable through a Go map's value type doesn't get its own TS class
// generated by this project's installed Wails version, unlike one
// reachable through a slice.
type AuthorProfile struct {
	SteamID string
	Profile steamapi.Profile
}

// AuthorProfileCache holds real Steam Community profile data (display
// name, avatar, member-since date) for a Workshop mod's creator, fetched
// once per SteamID64 and kept in memory for the app's runtime - see
// docs/steam-web-api.md. The zero value is ready to use.
type AuthorProfileCache struct {
	mu   sync.Mutex
	byID map[string]steamapi.Profile
	// fetch defaults to steamapi.GetPlayerProfile (see Get) - a field
	// rather than a direct call so tests can substitute a fake that never
	// makes a real network request.
	fetch func(ctx context.Context, steamID64 string) (steamapi.Profile, bool, error)
}

// Get returns real Steam Community profiles for every one of steamIDs
// (typically PublishedFileDetails.Creator values already fetched for this
// project's own purposes - this project never looks anyone up who isn't
// already mentioned in real Workshop data it fetched itself). An id
// already fetched in a previous call (this process, this session) is
// served from memory with no network call at all; only ids genuinely
// missing are fetched, with bounded concurrency. A profile Steam couldn't
// resolve (a bad id, or a transient failure) is simply absent from the
// result, not an error - matching this project's non-fatal-per-item
// philosophy elsewhere.
func (c *AuthorProfileCache) Get(ctx context.Context, steamIDs []string) (map[string]steamapi.Profile, error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.byID == nil {
		c.byID = map[string]steamapi.Profile{}
	}

	seen := make(map[string]bool, len(steamIDs))
	missing := make([]string, 0, len(steamIDs))
	for _, id := range steamIDs {
		if id == "" || seen[id] {
			continue
		}
		seen[id] = true
		if _, ok := c.byID[id]; !ok {
			missing = append(missing, id)
		}
	}

	if len(missing) > 0 {
		fetch := c.fetch
		if fetch == nil {
			fetch = steamapi.GetPlayerProfile
		}
		var mu sync.Mutex
		g, gctx := errgroup.WithContext(ctx)
		g.SetLimit(maxConcurrentProfileFetches)
		for _, id := range missing {
			g.Go(func() error {
				profile, ok, err := fetch(gctx, id)
				if err != nil || !ok {
					return nil
				}
				mu.Lock()
				c.byID[id] = profile
				mu.Unlock()
				return nil
			})
		}
		_ = g.Wait() // every real error is already swallowed per-item above
	}

	result := make(map[string]steamapi.Profile, len(steamIDs))
	for _, id := range steamIDs {
		if p, ok := c.byID[id]; ok {
			result[id] = p
		}
	}
	return result, nil
}
